-- Wspólny magazyn: publiczny podgląd, edycja tylko po zalogowaniu.
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  name text not null,
  emoji text not null default '📦',
  quantity integer not null default 1 check (quantity >= 1),
  created_at timestamptz not null default now()
);

alter table public.items enable row level security;

-- Usuń wcześniejsze otwarte polityki i polityki z poprzedniej wersji.
drop policy if exists "public read" on public.items;
drop policy if exists "public insert" on public.items;
drop policy if exists "public update" on public.items;
drop policy if exists "public delete" on public.items;
drop policy if exists "Public can read items" on public.items;
drop policy if exists "Admins can insert items" on public.items;
drop policy if exists "Admins can update items" on public.items;
drop policy if exists "Admins can delete items" on public.items;

-- Każdy może oglądać zawartość, także bez konta.
create policy "Public can read items"
on public.items for select
to anon, authenticated
using (true);

-- Zmiany wymagają zalogowanego użytkownika Supabase.
create policy "Admins can insert items"
on public.items for insert
to authenticated
with check (auth.uid() is not null);

create policy "Admins can update items"
on public.items for update
to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

create policy "Admins can delete items"
on public.items for delete
to authenticated
using (auth.uid() is not null);

grant select on public.items to anon, authenticated;
grant insert, update, delete on public.items to authenticated;
grant usage, select on sequence public.items_id_seq to authenticated;

do $$
begin
  alter publication supabase_realtime add table public.items;
exception when duplicate_object then
  null;
when duplicate_table then
  null;
end $$;
